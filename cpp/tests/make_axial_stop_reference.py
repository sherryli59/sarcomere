#!/usr/bin/env python3
"""Write tests/zdisc_axial_stop_reference.h from the standalone axial-stop law.

Reference values come from analysis/standalone_actn2_axial_contact.py
(axial_contact, whole-connector Gauss-Legendre with 4096 nodes), the law
that the C++ kernel compute_zdisc_axial_stop_contact implements.
usage: python make_axial_stop_reference.py ANALYSIS_DIR OUTPUT_HEADER
"""
import importlib.util
import sys
from pathlib import Path

import numpy as np

analysis = Path(sys.argv[1])
spec = importlib.util.spec_from_file_location('axial', analysis/'standalone_actn2_axial_contact.py')
axial = importlib.util.module_from_spec(spec)
sys.modules['axial'] = axial
spec.loader.exec_module(axial)
model = axial.Model()
assert axial.GATE_WIDTH == .010 and model.half == .750 and model.approach == .050
assert model.k == 1000. and model.slope == 30. and model.epsilon == .005 and model.radius == .130

rng = np.random.default_rng(20261029)
cases = []
straight = (np.zeros(3), np.array([1., 0, 0]))
tilted_axis = np.array([1, .03, -.02])/np.linalg.norm([1, .03, -.02])
tilted = (np.array([.008, -.003, .004]), tilted_axis)
# The probe that exposed the weighted law, and its longer variants.
for ell in (0., .040, .080):
    cases.append((*straight, [.730, .080, 0], [.730, .080+ell, 0]))
# Gate edge, onset, saturation transition, opposite tip, and a connector
# lying along the axis across the physical end.
cases += [(*straight, [.760, .125, 0], [.760, .145, 0]),
          (*straight, [.790, .050, .02], [.799, .070, -.02]),
          (*straight, [.700, .060, 0], [.740, .060, .03]),
          (*straight, [-.735, -.090, .02], [-.735, -.120, .03]),
          (*straight, [.700, .095, 0], [.820, .095, 0])]
for _ in range(24):
    p0 = rng.uniform([.65, .00, -.06], [.83, .15, .06])
    p1 = p0+rng.uniform([-.04, -.06, -.06], [.04, .06, .06])
    cases.append((*straight, p0, p1))
for _ in range(12):
    p0 = rng.uniform([.65, .06, -.03], [.83, .14, .03])
    p1 = p0+rng.uniform([-.02, .00, -.02], [.02, .07, .02])
    cases.append((*tilted, p0, p1))

lines = ['// Generated by make_axial_stop_reference.py from',
         '// analysis/standalone_actn2_axial_contact.py (4096-node Gauss); do not edit.',
         '#pragma once', '', 'struct AxialStopReference {',
         '    double center[3], axis[3], p0[3], p1[3];',
         '    double energy, force_i[3], force_j[3], torque_m[3];', '};', '',
         'inline const AxialStopReference kAxialStopReference[] = {']
fmt = lambda v: '{'+', '.join(f'{float(x):.17g}' for x in v)+'}'
for center, axis, p0, p1 in cases:
    e, fi, fj, tm = axial.axial_contact(np.asarray(p0, float), np.asarray(p1, float), model, center, axis, n=4096)
    lines.append(f'    {{{fmt(center)}, {fmt(axis)}, {fmt(p0)}, {fmt(p1)},')
    lines.append(f'     {float(e):.17g}, {fmt(fi)}, {fmt(fj)}, {fmt(tm)}}},')
lines += ['};', '']
Path(sys.argv[2]).write_text('\n'.join(lines))
print(f'{len(cases)} reference cases; nonzero energy in',
      sum(axial.axial_contact(np.asarray(c[2], float), np.asarray(c[3], float), model, c[0], c[1], n=256)[0] > 0 for c in cases))
