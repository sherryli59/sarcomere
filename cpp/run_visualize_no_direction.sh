#!/bin/bash
set -euo pipefail

# Usage:
#   ./run_visualize_no_direction.sh [MMDD]
# Example:
#   ./run_visualize_no_direction.sh 0312
# If MMDD is omitted, today's date is used.

DATE="${1:-$(date +%m%d)}"
SCRATCH_DIR="${SCRATCH_DIR:-/scratch/users/xsli/sarcomere}"
OUTPUT_DIR="${SCRATCH_DIR}/data${DATE}"
FRAME_BASE_DIR="${SCRATCH_DIR}/frames${DATE}"
LOG_DIR="${SCRATCH_DIR}/logs${DATE}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ANALYSIS_SCRIPT="${SCRIPT_DIR}/../analysis/visualize_traj.py"

if [[ ! -f "${ANALYSIS_SCRIPT}" ]]; then
  echo "Error: visualization script not found at ${ANALYSIS_SCRIPT}" >&2
  exit 1
fi

if [[ ! -d "${OUTPUT_DIR}" ]]; then
  echo "Error: output directory not found: ${OUTPUT_DIR}" >&2
  exit 1
fi

# Match the no-direction outputs generated by sweep_params_no_direction.sbatch
shopt -s nullglob
h5_files=("${OUTPUT_DIR}"/A*_M*_lt*_nodir_L12x2x2.h5)

if [[ ${#h5_files[@]} -eq 0 ]]; then
  echo "No matching .h5 files found in ${OUTPUT_DIR}" >&2
  exit 1
fi

mkdir -p "${FRAME_BASE_DIR}" "${LOG_DIR}"

# Activate environment if micromamba is available
if command -v micromamba >/dev/null 2>&1; then
  eval "$(micromamba shell hook --shell bash)"
  micromamba activate sarcomere
  unset PYTHONPATH
fi

for h5 in "${h5_files[@]}"; do
  base_name="$(basename "${h5}" .h5)"
  frame_dir="${FRAME_BASE_DIR}/${base_name}"
  log_file="${LOG_DIR}/${base_name}.vis.out"

  mkdir -p "${frame_dir}"

  echo "[VIS] ${base_name}"
  python "${ANALYSIS_SCRIPT}" \
    --filename="${h5}" \
    --frame_dir="${frame_dir}" \
    --Lx=12 --Ly=2 --Lz=2 \
    --myosin_radius=0.05 \
    --sample_every=10 \
    --start_frame=0 \
    --myosin_display cb_attached \
    > "${log_file}" 2>&1

done

echo "Done. Visualization complete for ${#h5_files[@]} file(s)."
